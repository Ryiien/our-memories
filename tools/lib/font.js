export const CELL_HEIGHT = 9; // 7 + 2 descender rows
export const LINE_HEIGHT = 10;

/**
 * Pack every glyph into a PNG and write the matching BMFont XML.
 * @returns {{ png: Canvas, xml: string, chars: string }}
 */
export function buildFont({ face = 'cosy', file = 'font.png' } = {}) {
  const entries = Object.entries(G);
  const sheetW = 128;
  const placed = [];
  let x = 1;
  let y = 1;
  for (const [ch, rows] of entries) {
    const w = rows[0].length;
    rows.forEach((r, i) => {
      if (r.length !== w) throw new Error(`Glyph "${ch}" row ${i} has the wrong width`);
    });
    if (x + w + 1 > sheetW) {
      x = 1;
      y += CELL_HEIGHT + 1;
    }
    placed.push({ ch, rows, x, y, w });
    x += w + 1;
  }
  const sheetH = y + CELL_HEIGHT + 1;
  const png = new Canvas(sheetW, sheetH);
  for (const g of placed) {
    g.rows.forEach((row, ry) => {
      for (let rx = 0; rx < row.length; rx++) if (row[rx] === '#') png.px(g.x + rx, g.y + ry, '#ffffff');
    });
  }

  const charsXml = placed
    .map((g) => {
      const advance = g.ch === ' ' ? 3 : g.w + 1;
      return `    <char id="${g.ch.codePointAt(0)}" x="${g.x}" y="${g.y}" width="${g.w}" height="${CELL_HEIGHT}" xoffset="0" yoffset="0" xadvance="${advance}" page="0" chnl="15" />`;
    })
    .join('\n');

  const xml = `<?xml version="1.0"?>
<!-- Generated by tools/make-placeholders.js. Any BMFont-format (XML) font works here. -->
<font>
  <info face="${face}" size="${CELL_HEIGHT}" bold="0" italic="0" charset="" unicode="1" stretchH="100" smooth="0" aa="0" padding="0,0,0,0" spacing="1,1" />
  <common lineHeight="${LINE_HEIGHT}" base="7" scaleW="${sheetW}" scaleH="${sheetH}" pages="1" packed="0" />
  <pages>
    <page id="0" file="${file}" />
  </pages>
  <chars count="${placed.length}">
${charsXml}
  </chars>
</font>
`;
  return { png, xml, chars: placed.map((g) => g.ch).join('') };
}
