// Accented letters: a base letter plus a mark drawn in the top two rows.
const MARKS = {
  acute: ['..#', '.#.'],
  grave: ['#..', '.#.'],
  circ: ['.#.', '#.#'],
  uml: ['#.#', '...'],
  tilde: ['.##.#', '#.##.'],
};
function accented(base, mark) {
  const rows = G[base].map((r) => r.split(''));
  const m = MARKS[mark];
  const w = rows[0].length;
  const ox = Math.floor((w - m[0].length) / 2);
  for (let y = 0; y < 2; y++) {
    rows[y] = rows[y].map(() => '.');
    for (let x = 0; x < m[y].length; x++) if (m[y][x] === '#') rows[y][ox + x] = '#';
  }
  return rows.map((r) => r.join(''));
}
